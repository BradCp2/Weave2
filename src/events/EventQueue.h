/**
 * @file EventQueue.h
 * @brief Declares the thread-safe application event queue.
 */

#ifndef WEAVE2_EVENTQUEUE_H
#define WEAVE2_EVENTQUEUE_H

#include <string>
#include <mutex>
#include <condition_variable>
#include <queue>

namespace weave::events
{
    /**
    * @enum EventType
    * @brief Defines the severity or category of an application event.
    */
    enum class EventType
    {
        Error,
        Warning,
        Information,
        Success,
        Debug
    };

    /**
    * @enum EventSource
    * @brief Identifies the application component that generated an event.
    */
    enum class EventSource
    {
        Parser,
        Dispatcher,
        Command,
        Worker
    };

    /**
    * @struct Event
    * @brief Represents an event generated by an application component.
    *
    * Contains the event type, originating component, associated message
    * and identifier used to associate related events.
    */
    struct Event
    {
        EventType type;       /**< @brief Event category. */
        EventSource source;   /**< @brief Component that generated the event. */
        std::string message;  /**< @brief Message describing the event. */
        std::size_t id;       /**< @brief Identifier associated with the event. */
    };

    /**
    * @class EventQueue
    * @brief Thread-safe FIFO queue for application events.
    *
    * Provides a mechanism for application components and worker threads
    * to publish events and for consumers to retrieve them.
    *
    * Uses a mutex to protect access to the underlying queue and a
    * condition variable to allow consumers to wait for new events.
    *
    * Supports shutdown through stop(), allowing waiting consumers
    * to be notified when the queue is stopping.
    */
    class EventQueue
    {
        public:
        /**
         * @brief Constructs and empty event queue.
         */
        EventQueue();

        /**
         * @brief Adds an event to the queue.
         *
         * Adds an event to the back of the queue and notifies a waiting
         * consumer that an event is available.
         *
         * @param type Category of the event.
         * @param source Component generating the event.
         * @param message Message associated with the event.
         * @param id Optional identifier for associating related events.
         */
        void pushEvent(EventType type, EventSource source, const std::string& message, std::size_t id = 0);

        /**
        * @brief Waits for and retrieves the next available event.
        *
        * Blocks until an event becomes available or the queue is stopped.
        * Retrieves events in FIFO order.
        *
        * @param event Reference to the Event object that receives the retrieved event.
        *
        * @return True if an event was retrieved, false if the queue is stopped
        * and no events remain.
        */
        bool waitForEvent(Event& event);

        /**
         * @brief Signals the queue to stop accepting new events.
         *
         * Wakes all waiting consumers. Events already in the queue can
         * still be retrieved before consumers are notified that the
         * queue has stopped.
         */
        void stop();

        private:
        std::queue<Event> events_;
        std::mutex mutex_;
        std::condition_variable condition_;
        bool stopping_ = false;
    };
} // events

#endif //WEAVE2_EVENTQUEUE_H
